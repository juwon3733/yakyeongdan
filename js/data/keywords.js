// 글 안에 나오는 키워드 설명을 모아 한 덩어리로 (없으면 '')
// 「빛」(별빛)·「쌍」(쌍둥이)처럼 다른 낱말에 섞이는 것은 따로 거른다. 상태 칩은 kwOne으로 이름을 바로 찾는다.
const SCAN = { '빛': null, '멈춤': null, '현상금': /현상금/, '쌍': /쌍(?!둥|검|그|염)/, '힘': /힘 ?[+\d]/, '잠': /잠(든|들|$| )/, '반격': /반격/, '안내': /행동을 (다음|바로 전)|행동을 바꾼|안내/ };
export function kwTip(text) {
  const s = String(text || '');
  return Object.keys(KW).filter(k => k in SCAN ? SCAN[k] && SCAN[k].test(s) : s.includes(k)).map(k => `${k}: ${KW[k]}`).join('\n');
}
export const kwOne = k => KW[k] ? `${k}: ${KW[k]}` : '';
